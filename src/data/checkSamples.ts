export type CheckDemoChip = {
  value: string
  display: string
  kind: 'scam' | 'official'
}

function chipsFrom(seeds: Seed[], kind: 'scam' | 'official'): CheckDemoChip[] {
  return seeds
    .filter((seed) => seed.chip === kind)
    .map((seed) => ({
      value: looksLikeHost(seed.value) ? `https://${seed.value}` : seed.value,
      display: seed.value,
      kind,
    }))
}

function looksLikeHost(value: string) {
  return value.includes('.') && !value.includes('@') && !/^\d+$/.test(value)
}

