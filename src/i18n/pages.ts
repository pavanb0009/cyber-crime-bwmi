type Pages = typeof en

function merge(extra: unknown): Pages {
  const walk = (base: unknown, over: unknown): unknown => {
    if (!over || typeof over !== 'object' || Array.isArray(over) || !base || typeof base !== 'object' || Array.isArray(base)) {
      return over ?? base
    }
    const out: Record<string, unknown> = { ...(base as Record<string, unknown>) }
    for (const [key, value] of Object.entries(over as Record<string, unknown>)) {
      out[key] = walk(out[key], value)
    }
    return out
  }
  return walk(en, extra) as Pages
}

